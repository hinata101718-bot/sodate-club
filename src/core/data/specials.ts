/** 悪い特殊能力のうち、ポジションでつかないもの */
export function badAllowed(name: string, pos: Pos): boolean {
  if (name === '守備をサボる') return pos === 'WG' || pos === 'ST' || pos === 'AM';
  if (name === 'ラフプレイヤー') return pos !== 'GK' && pos !== 'WG' && pos !== 'ST';
  if (name === '判断が遅い') return pos !== 'GK';
  return true;
}
